// Мягкая сверка свободного ввода для словарных курсов.
//
// Отдельный модуль без импортов контента: его тянут и клиентские компоненты,
// а src/content/index.ts подтягивает за собой все курсы целиком.

// Регистр, пунктуация и апострофы не должны решать, засчитан ответ или нет:
// фразу «Can you speak slower?» иначе не ввести без придирок к «?».
// Апострофы выкидываются без пробела ("don't" → "dont"), остальные символы
// становятся разделителями ("hard-working" → "hard working").
export function normalizeText(s: string): string {
   return s
      .toLowerCase()
      .replace(/['’‘`ʼ]/g, "")
      .replace(/[^\p{L}\p{N}]+/gu, " ")
      .replace(/\s+/g, " ")
      .trim();
}
