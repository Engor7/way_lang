// Курс «Три формы глагола»: частотные глаголы (включая правильные — чтобы
// закрепить, что особых форм у них нет) + добор популярных неправильных.
// У каждого глагола: формы, перевод и три простых примера — Present / Past /
// Present Perfect. Форма глагола в примере помечена {скобками}: из неё
// строится упражнение «вставь форму» и подсветка в карточке. Вариативные
// формы записываются через слэш ("got/gotten") — проверка принимает любой
// вариант или оба сразу; в примерах отображается первый вариант.
//
// Item для общего механизма: prompt — база, answer — «V2 — V3», hint — перевод.

import type { Course, Item } from "./types";

export type VerbExample = {
   en: string; // форма в {скобках}: "Yesterday I {went} home late."
   ru: string;
};

export type VerbEntry = {
   base: string;
   past: string;
   participle: string;
   ru: string;
   examples: [VerbExample, VerbExample, VerbExample];
};

// Подписи к формам/примерам — по индексу (0 — база, 1 — past, 2 — participle)
export const FORM_LABELS = [
   "1-я форма · настоящее (Present)",
   "2-я форма · прошедшее (Past)",
   "3-я форма · перфект, после have/has",
] as const;

export type VerbVariant =
   | "en-ru" // глагол → выбрать перевод
   | "ru-en" // перевод → выбрать/ввести глагол
   | "forms" // база → формы (выбор или ввод)
   | "gap"; // пример с пропуском → ввести форму

function v(
   base: string,
   past: string,
   participle: string,
   ru: string,
   enPresent: string,
   ruPresent: string,
   enPast: string,
   ruPast: string,
   enPerfect: string,
   ruPerfect: string,
): VerbEntry {
   return {
      base,
      past,
      participle,
      ru,
      examples: [
         { en: enPresent, ru: ruPresent },
         { en: enPast, ru: ruPast },
         { en: enPerfect, ru: ruPerfect },
      ],
   };
}

