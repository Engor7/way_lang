// «Карточка-разбор» глагола: три формы с подписями и примерами. Показывается
// на обороте флеш-карточки и как объяснение после каждого ответа в тренажёре.
export type VerbCardData = {
   base: string;
   ru: string;
   forms: string; // "went — gone"
   rows: {
      label: string; // подпись формы (FORM_LABELS)
      form: string; // сама форма: "go" / "went" / "gone"
      en: string; // пример с формой в {скобках}
      ru: string;
   }[];
};

export function verbCardOf(itemId: string): VerbCardData | null {
   const entry = verbEntryOf(itemId);
   if (!entry) {
      return null;
   }
   const forms = [entry.base, entry.past, entry.participle];
   return {
      base: entry.base,
      ru: entry.ru,
      forms: verbForms(entry),
      rows: entry.examples.map((example, i) => ({
         label: FORM_LABELS[i],
         form: forms[i],
         en: example.en,
         ru: example.ru,
      })),
   };
}

// Разбор примера: часть до формы, сама форма (первый вариант), часть после,
// чистый текст, текст с пропуском и допустимые ответы для «вставь форму»
export function splitExample(en: string): {
   before: string;
   form: string;
   after: string;
   clean: string;
   gapped: string;
   answers: string[];
} {
   const match = en.match(/^(.*)\{([^}]+)\}(.*)$/);
   if (!match) {
      return {
         before: en,
         form: "",
         after: "",
         clean: en,
         gapped: en,
         answers: [],
      };
   }
   const [, before, braced, after] = match;
   const answers = braced.split("/");
   const form = answers[0];
   return {
      before,
      form,
      after,
      clean: `${before}${form}${after}`,
      gapped: `${before}___${after}`,
      answers,
   };
}

function normalizeToken(s: string): string {
   return s.toLowerCase().replace(/[^a-z'/]/g, "");
}

// Проверка «вставь форму»: точная форма из примера (любой из вариантов)
export function checkVerbGap(example: VerbExample, input: string): boolean {
   const { answers } = splitExample(example.en);
   const got = normalizeToken(input);
   return answers.some((answer) => normalizeToken(answer) === got);
}

// Проверка свободного ввода форм: "went gone", "went — gone", "went, gone".
// Слот с вариантами ("got/gotten") принимает любой вариант или оба сразу.
export function checkVerbForms(expected: string, input: string): boolean {
   const slots = expected
      .split("—")
      .map((part) => part.trim().toLowerCase().split("/"));
   const tokens = input
      .toLowerCase()
      .split(/[\s,;/—–-]+/)
      .filter((token) => token.length > 0);

   // слот съедает либо один из вариантов, либо все подряд ("was were");
   // жадность не годится ("learnt learned" — это два слота), поэтому перебор
   function matchFrom(slot: number, i: number): boolean {
      if (slot === slots.length) {
         return i === tokens.length;
      }
      const alternatives = slots[slot];
      if (
         alternatives.includes(tokens[i] ?? "") &&
         matchFrom(slot + 1, i + 1)
      ) {
         return true;
      }
      return (
         alternatives.length > 1 &&
         alternatives.every((alt, j) => tokens[i + j] === alt) &&
         matchFrom(slot + 1, i + alternatives.length)
      );
   }
   return matchFrom(0, 0);
}

// «Правильная» форма прошедшего для дистракторов: work → worked, try → tried
function regularized(base: string): string {
   if (base.endsWith("e")) {
      return `${base}d`;
   }
   if (/[bcdfghjklmnpqrstvwxz]y$/.test(base)) {
      return `${base.slice(0, -1)}ied`;
   }
   return `${base}ed`;
}

// Неправильные варианты «V2 — V3» этого же глагола — дистракторы для выбора:
// перепутанные и «регуляризованные» формы куда полезнее форм чужих глаголов
export function verbFormsDistractors(entry: VerbEntry): string[] {
   const { base, past, participle } = entry;
   const correct = verbForms(entry);
   const reg = regularized(base);
   const candidates = [
      `${reg} — ${reg}`,
      `${past} — ${past}`,
      `${participle} — ${participle}`,
      `${participle} — ${past}`,
      `${base} — ${participle}`,
      `${past} — ${base}`,
      `${base} — ${base}`,
      // для неизменяемых глаголов (put — put — put) вариантов выше мало
      `${base} — ${reg}`,
      `${reg} — ${base}`,
   ];
   return [...new Set(candidates)].filter((option) => option !== correct);
}

